const renderers = { ...icons, ...brandPaths } satisfies Record<LinkIconId, PhosphorIcon | string>;

export function LinkIcon({
  icon,
  platform = 'custom',
  size = 20,
}: {
  icon?: LinkIconId;
  platform?: Platform;
  size?: number;
}) {
  const id = icon ?? linkPresets[platform]?.icon;
  const renderer = renderers[id];
  if (typeof renderer === 'string')
    return (
      <svg width={size} height={size} viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">
        <path d={renderer} />
      </svg>
    );
  const Icon = renderer ?? ChainLinkIcon;
  return <Icon weight="regular" size={size} aria-hidden="true" />;
}

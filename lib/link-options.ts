export function findIcons(query: string, category: IconCategory | 'All' = 'All') {
  const terms = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
  return iconCatalog.filter(
    (icon) =>
      (category === 'All' || icon.category === category) &&
      terms.every((term) =>
        `${icon.id} ${icon.label} ${icon.keywords}`.toLowerCase().includes(term),
      ),
  );
}
